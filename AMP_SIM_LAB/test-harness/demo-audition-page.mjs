function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function formatDb(value) {
  return Number.isFinite(value) ? `${value.toFixed(2)} dBFS` : "(none)";
}

function renderResultKey(result) {
  return result?.jobId || result?.job_id || "";
}

function matrixJobKey(job) {
  return job?.job_id || job?.jobId || "";
}

function clipHrefFor({ processedWavPath, reportsDir: baseReportsDir, clipExists }) {
  if (!processedWavPath || !clipExists(processedWavPath)) {
    return null;
  }

  return path.relative(baseReportsDir, processedWavPath).replaceAll(path.sep, "/");
}

function rowFromMatrixJob({ job, result, reportsDir: baseReportsDir, clipExists }) {
  const clipHref = clipHrefFor({
    processedWavPath: result?.processedWavPath,
    reportsDir: baseReportsDir,
    clipExists
  });
  const metrics = result?.metrics;
  const statusLabel = result?.status || (job.status === "planned" ? "planned local render" : job.status || "planned local render");

  return {
    jobId: matrixJobKey(job),
    presetName: job.preset_name || job.presetName || result?.presetId || "(unnamed)",
    category: job.preset_category || job.category || "(unspecified)",
    sourceSlot: job.di_slot || job.sourceSlot || "(unspecified)",
    statusLabel,
    hookLabel: result?.renderHookStatus || "matrix only",
    clipHref,
    clipLabel: clipHref ? path.basename(result.processedWavPath) : "(none)",
    peakLabel: formatDb(metrics?.peakDbfs),
    clippingLabel: Number.isFinite(metrics?.clippedSamples) ? String(metrics.clippedSamples) : "(none)",
    messages: [...(job.messages ?? []), ...(result?.messages ?? [])]
  };
}

function rowFromRenderResult({ result, reportsDir: baseReportsDir, clipExists }) {
  const clipHref = clipHrefFor({
    processedWavPath: result?.processedWavPath,
    reportsDir: baseReportsDir,
    clipExists
  });
  const metrics = result?.metrics;

  return {
    jobId: renderResultKey(result),
    presetName: result?.presetId || "(unnamed)",
    category: "(from render report)",
    sourceSlot: "(from render report)",
    statusLabel: result?.status || "unknown",
    hookLabel: result?.renderHookStatus || "unknown",
    clipHref,
    clipLabel: clipHref ? path.basename(result.processedWavPath) : "(none)",
    peakLabel: formatDb(metrics?.peakDbfs),
    clippingLabel: Number.isFinite(metrics?.clippedSamples) ? String(metrics.clippedSamples) : "(none)",
    messages: result?.messages ?? []
  };
}

export function createDemoAuditionViewModel({
  generatedAt = new Date().toISOString(),
  reportsDir: baseReportsDir = reportsDir,
  auditionMatrix = null,
  renderResults = null,
  clipExists = fsSync.existsSync
} = {}) {
  const resultsByJob = new Map((renderResults?.results ?? []).map((result) => [renderResultKey(result), result]));
  const matrixJobs = auditionMatrix?.jobs ?? [];
  const rows = matrixJobs.map((job) => {
    const result = resultsByJob.get(matrixJobKey(job));
    resultsByJob.delete(matrixJobKey(job));
    return rowFromMatrixJob({ job, result, reportsDir: baseReportsDir, clipExists });
  });

  for (const result of resultsByJob.values()) {
    rows.push(rowFromRenderResult({ result, reportsDir: baseReportsDir, clipExists }));
  }

  const finalRows = rows.length > 0 ? rows : structuredClone(placeholderRows);
  const renderedClips = finalRows.filter((row) => row.statusLabel === "rendered" && row.clipHref).length;
  const mode = renderedClips > 0 ? "render-results" : rows.length > 0 ? "dry-run" : "placeholder";

  return {
    generatedAt,
    summary: {
      mode,
      jobs: finalRows.length,
      renderedClips,
      playableClips: finalRows.filter((row) => row.clipHref).length
    },
    rows: finalRows
  };
}

export function createDemoAuditionHtml(model) {
  const rows = model.rows
    .map((row) => {
      const clipCell = row.clipHref
        ? `<a href="${escapeHtml(row.clipHref)}">${escapeHtml(row.clipLabel)}</a><br><audio controls preload="none" src="${escapeHtml(row.clipHref)}"></audio>`
        : escapeHtml(row.clipLabel);
      const messages = row.messages.length > 0 ? row.messages.map(escapeHtml).join("<br>") : "(none)";

      return `<tr>
  <td>${escapeHtml(row.jobId)}</td>
  <td>${escapeHtml(row.presetName)}</td>
  <td>${escapeHtml(row.category)}</td>
  <td>${escapeHtml(row.sourceSlot)}</td>
  <td>${escapeHtml(row.statusLabel)}</td>
  <td>${escapeHtml(row.hookLabel)}</td>
  <td>${clipCell}</td>
  <td>${escapeHtml(row.peakLabel)}</td>
  <td>${escapeHtml(row.clippingLabel)}</td>
  <td>${messages}</td>
</tr>`;
    })
    .join("\n");

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Internal Demo Audition</title>
  <style>
    body { background: #101216; color: #e5edf5; font-family: Arial, sans-serif; margin: 32px; }
    h1 { margin-bottom: 4px; }
    p { color: #aab7c4; max-width: 920px; }
    table { border-collapse: collapse; width: 100%; margin: 18px 0 32px; }
    th, td { border: 1px solid #334155; padding: 8px; text-align: left; vertical-align: top; }
    th { background: #1f2937; }
    audio { width: 260px; margin-top: 6px; }
    a { color: #93c5fd; }
  </style>
</head>
<body>
  <h1>Internal Demo Audition</h1>
  <p>Generated: ${escapeHtml(model.generatedAt)}</p>
  <p>Internal demo/audition only. This local page lists dry-run placeholders and any existing local render clips; it does not approve public release.</p>
  <p>Mode: ${escapeHtml(model.summary.mode)} | Jobs: ${model.summary.jobs} | Rendered clips: ${model.summary.renderedClips} | Playable clips: ${model.summary.playableClips}</p>
  <table>
    <thead>
      <tr>
        <th>Job</th>
        <th>Preset</th>
        <th>Category</th>
        <th>Source Slot</th>
        <th>Status</th>
        <th>Hook</th>
        <th>Clip</th>
        <th>Peak</th>
        <th>Clipped Samples</th>
        <th>Messages</th>
      </tr>
    </thead>
    <tbody>${rows}</tbody>
  </table>
</body>
</html>`;
}

async function readJsonIfExists(filePath) {
  try {
    return JSON.parse(await fs.readFile(filePath, "utf8"));
  } catch {
    return null;
  }
}

export async function writeDemoAuditionPage({
  reportPath = path.join(reportsDir, "demo-audition.html"),
  auditionMatrixPath = path.join(reportsDir, "audition-matrix.json"),
  renderResultsPath = path.join(reportsDir, "render-results.json")
} = {}) {
  const auditionMatrix = await readJsonIfExists(auditionMatrixPath);
  const renderResults = await readJsonIfExists(renderResultsPath);
  const model = createDemoAuditionViewModel({
    reportsDir: path.dirname(reportPath),
    auditionMatrix,
    renderResults
  });

  await fs.mkdir(path.dirname(reportPath), { recursive: true });
  await fs.writeFile(reportPath, createDemoAuditionHtml(model), "utf8");
  return { reportPath, model };
}
